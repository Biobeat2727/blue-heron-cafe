import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../lib/eventSchema.js', import.meta.url), 'utf8');
const { generateEventSchema: schema, eventDates } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const base = { title: 'Community Show', slug: 'community-show', date: '2026-09-19', time: '6pm - 9pm' };
assert.deepEqual(eventDates(base.date, base.time), { startDate: '2026-09-19T18:00:00', endDate: '2026-09-19T21:00:00' });
assert.equal(eventDates('2026-12-31', '11pm–1am').endDate, '2027-01-01T01:00:00');
assert.equal(eventDates(base.date, '18:00 to 21:00').startDate, '2026-09-19T18:00:00');
assert.deepEqual(eventDates(base.date, '6-9pm'), { startDate: base.date });
assert.deepEqual(eventDates(base.date, null), { startDate: base.date });
assert.equal(eventDates('2026-02-30', '6pm'), null);
assert.equal(schema(base).offers, undefined);
assert.equal(schema(base).isAccessibleForFree, undefined);
assert.equal(schema({ ...base, admission: 'Free entry' }).offers.price, 0);
assert.equal(schema({ ...base, admission: '$15' }).offers.price, 15);
const charity = schema({ ...base, description: 'Benefit for the food bank', admission: 'Suggested donation $20' });
assert.match(charity.description, /food bank/);
assert.match(charity.description, /Suggested donation/);
assert.equal(charity.offers, undefined);
const tickets = schema({ ...base, ticketUrl: 'https://example.com/tickets', admission: '$10–$20' });
assert.equal(tickets.offers.url, 'https://example.com/tickets');
assert.equal(tickets.offers.price, undefined);
assert.equal(tickets.offers.availability, undefined);
assert.equal(schema({ ...base, ticketUrl: 'javascript:alert(1)' }).offers, undefined);
assert.equal(schema({ ...base, isPrivate: true }), null);
assert.equal(schema({ ...base, title: 'Private Wedding' }), null);
assert.equal(schema(base).location.address.addressLocality, 'Sandpoint');
assert.equal(schema(base).url, 'https://www.blueheronsamuels.com/events/community-show');
console.log('Event schema checks passed: dates, overnight rollover, optional admission, donations, tickets, private events, and address.');
